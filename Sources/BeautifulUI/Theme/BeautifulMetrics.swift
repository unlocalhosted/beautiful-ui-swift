import SwiftUI

/// Deliberately small spacing and sizing vocabulary used throughout the library.
public enum BeautifulMetrics {
    public static let micro: CGFloat = 4
    public static let compact: CGFloat = 6
    public static let regular: CGFloat = 8
    public static let roomy: CGFloat = 12
    public static let section: CGFloat = 16
    public static let cornerRadius: CGFloat = 10
    public static let controlHeight: CGFloat = 32
}
